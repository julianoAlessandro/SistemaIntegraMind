    private void btnSalvar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvar1ActionPerformed

        try {

            UsuarioJPA usuarioJPA = new UsuarioJPA();
            Usuarios usuario = lerCamposUsuario();

            if (usuario.getId() == null) {

                usuarioJPA.cadastrarUsuario(usuario);

                JOptionPane.showMessageDialog(
                        this,
                        "Usuário cadastrado com sucesso!"
                );

                System.out.println("Usuário cadastrado com sucesso. ID -> " + usuario.getId());

            } else {

                usuarioJPA.atualizarUsuario(usuario);

                JOptionPane.showMessageDialog(
                        this,
                        "Usuário atualizado com sucesso!"
                );

                System.out.println("Usuário atualizado. ID -> " + usuario.getId());
            }

            limparTelaCadastroUsuario();
            carregarTabelaUsuarios();
            abas.setSelectedIndex(1);

        } catch (Exception e) {

            e.printStackTrace();

            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao salvar usuário:\n" + e.getMessage(),
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );

            abas.setSelectedIndex(0);
        }
    }//GEN-LAST:event_btnSalvar1ActionPerformed


