    private Usuarios lerCamposUsuario() {

        Usuarios usuario = new Usuarios();
        usuario.setId(idUsuario);
        usuario.setUsuario(txtNome.getText().trim());
        usuario.setSenha(txtSenha.getText());

        //2026-07-18 Guilherme: Pega o objeto Cargo completo que já contém o ID
        Cargo cargoSelecionado = (Cargo) txtCargo.getSelectedItem();
        usuario.setCargo(cargoSelecionado);

        return usuario;
    }

    private void limparTelaCadastroUsuario() {
        txtNome.setText("");
        txtSenha.setText("");
        txtCargo.setSelectedIndex(0);
        txtNome.requestFocus();

        idUsuario = null;
    }

    public void carregarTabelaUsuarios() {
        try {
            UsuarioJPA jpa = new UsuarioJPA();
            List<Usuarios> listUsuarios = jpa.listarUsuarios();

            String[] colunas = {"ID", "Nome / Usuário", "Cargo"};

            DefaultTableModel model = new DefaultTableModel(colunas, 0) {
                @Override
                public boolean isCellEditable(int row, int column) {
                    return false;
                }
            };

            for (Usuarios u : listUsuarios) {
                model.addRow(new Object[]{
                    u.getId(),
                    u.getUsuario(),
                    u.getCargo().getNome()
                });
            }

            tabUsuarios.setModel(model);

            tabUsuarios.getColumnModel().getColumn(0).setMinWidth(0);
            tabUsuarios.getColumnModel().getColumn(0).setMaxWidth(0);
            tabUsuarios.getColumnModel().getColumn(0).setWidth(0);

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Erro ao carregar lista de usuários: " + e.getMessage());
        }
    }

    private void carregarComboBoxCargos() {
        try {
            CargoJPA cargoJPA = new CargoJPA();
            List<Cargo> listaCargos = cargoJPA.listarCargos();

            txtCargo.removeAllItems();

            for (Cargo c : listaCargos) {
                txtCargo.addItem(c); //2026-07-18 Guilherme: Adiciona o objeto Cargo diretamente
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Erro ao carregar os cargos no formulário: " + e.getMessage());
        }
    }

